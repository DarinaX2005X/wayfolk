import path from 'node:path';
import { chromium } from 'playwright';
import { createServer } from 'vite';
const server = await createServer({ configFile: path.resolve('tests/together/preview/vite.config.ts') });
await server.listen();
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const host = await ctx.newPage();
host.on('console', (m) => console.log('host:', m.text()));
await host.goto('http://127.0.0.1:5185/?role=host');
await host.waitForFunction(() => window.__tg?.live.code, null, { timeout: 60000 });
const code = await host.evaluate(() => window.__tg.live.code);
const guest = await ctx.newPage();
await guest.goto(`http://127.0.0.1:5185/?role=guest&code=${code}`);
await guest.waitForFunction(() => window.__tg?.events.includes('tg-dock:Mira'), null, { timeout: 60000 });
await host.evaluate(() => window.__tg.fast(17));
const out = await host.evaluate(() => {
  const t = window.__tg.together;
  const n = t.neighbours[0];
  const d = t.debug;
  const c = n.coils.near.position;
  window.__tg.eyeAt(n.spots.near.pos.x, n.spots.near.pos.y + 1.15, n.spots.near.pos.z, n.spots.near.rotY, -0.12);
  const s = window.__tg.screen(c.x, c.y + 0.6, c.z);
  return { building: Boolean(d.building), docked: n.docked, role: d.ctx.role(), targets: n.targets().length, s, coil: c.toArray(), spot: n.spots.near.pos.toArray() };
});
console.log(JSON.stringify(out));
await host.mouse.click(out.s.x, out.s.y);
await host.mouse.move(out.s.x, out.s.y);
await host.mouse.down();
await host.waitForTimeout(300);
console.log(await host.evaluate(() => JSON.stringify({ near: window.__tg.together.neighbours[0].hold.near, ev: window.__tg.events.slice(-5) })));
await host.screenshot({ path: 'tests/together/out/debug.png' });
await browser.close();
await server.close();
