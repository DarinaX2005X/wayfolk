#!/usr/bin/env node
/**
 * Builds api/_bundle.js from api/_routes.ts.
 *
 *   node tools/dev-api/bundle.mjs           write the bundle
 *   node tools/dev-api/bundle.mjs --check   exit 1 when the committed bundle is out of date
 *
 * Why the functions load a bundle. Vercel does not bundle files in api/: it compiles
 * each TypeScript file on its own and runs the result as an ES module (package.json has
 * "type": "module"). Node then resolves imports exactly as written, so `./limits` without
 * an extension, or a JSON import without an import attribute, fails on the first request
 * with ERR_MODULE_NOT_FOUND while the build is green. The server runs the same code as
 * the client where they must agree (the recorded answers of the examples, the contract
 * types, the engine's checks), and those files are written for Vite. Bundling them here
 * gives the functions one plain JavaScript file whose only outside import is
 * @vercel/blob, and that file can be loaded in plain Node before a deployment
 * (tests/api/bundle.test.ts does it).
 *
 * The bundle is committed. Run this script (or `npm test`, which runs it first) after a
 * change in api/ or in anything it imports; tests/api/bundle.test.ts fails when the
 * bundle on disk is stale.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const ENTRY = 'api/_routes.ts';
export const BUNDLE_PATH = path.join(ROOT, 'api', '_bundle.js');

const BANNER = [
  '// GENERATED by tools/dev-api/bundle.mjs from api/_routes.ts. Do not edit.',
  '// Regenerate after changes in api/ or in what it imports:',
  '//   node tools/dev-api/bundle.mjs',
].join('\n');

/** The bundle text, built in memory. */
export async function buildBundle() {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [ENTRY],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    // The SDK stays a real dependency: Vercel traces it from node_modules.
    external: ['@vercel/blob'],
    // Vite constants that shared modules may read; there is no Vite on the server.
    define: {
      'import.meta.env.DEV': 'false',
      'import.meta.env.PROD': 'true',
      'import.meta.env.SSR': 'true',
    },
    banner: { js: BANNER },
    legalComments: 'none',
    charset: 'utf8',
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

const sameText = (a, b) => a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');

/** True when api/_bundle.js exists and matches the sources. */
export async function bundleIsFresh() {
  const [built, onDisk] = await Promise.all([buildBundle(), readFile(BUNDLE_PATH, 'utf8').catch(() => null)]);
  return onDisk !== null && sameText(built, onDisk);
}

async function main() {
  if (process.argv.includes('--check')) {
    if (await bundleIsFresh()) {
      console.log('api/_bundle.js is up to date');
      return;
    }
    console.error('api/_bundle.js is missing or out of date. Run: node tools/dev-api/bundle.mjs');
    process.exitCode = 1;
    return;
  }
  const text = await buildBundle();
  await writeFile(BUNDLE_PATH, text, 'utf8');
  console.log(`api/_bundle.js written (${(Buffer.byteLength(text) / 1024).toFixed(1)} KB)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    const errors = err?.errors;
    if (Array.isArray(errors)) {
      for (const e of errors) console.error(`${e.location?.file ?? ''}:${e.location?.line ?? ''} ${e.text}`);
    } else {
      console.error(err);
    }
    process.exitCode = 1;
  });
}
