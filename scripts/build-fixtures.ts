/**
 * Builds what the samples need from their sources:
 *
 *   content/samples/texts.generated.ts    the texts of content/samples/<id>/*.md as a module
 *   content/answers/<id>.events.json      the saved copy of the sample's run (replay.ts),
 *                                         from its recording on a jumping clock
 *   public/samples/<id>/                  the deliverable to open: a site's files, or a
 *                                         plan's page with its CSV and calendar
 *
 * Everything after the texts comes from replaying content/answers/<id>.live.json with
 * every check running, so it is what a person gets on the device.
 *
 *   npm run fixtures              write
 *   npm run fixtures -- --check   only compare; exit 1 when something is out of date
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AnswerSet, SampleId, TaskResult } from '../src/agents/types';
import { toCsv, toIcs, toPlanPage } from '../src/agents/engine/export';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SAMPLES_DIR = path.join(ROOT, 'content', 'samples');
const ANSWERS_DIR = path.join(ROOT, 'content', 'answers');
const PUBLIC_DIR = path.join(ROOT, 'public', 'samples');
const check = process.argv.includes('--check');
const stale: string[] = [];

function put(file: string, text: string): void {
  const old = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (old === text) return;
  stale.push(path.relative(ROOT, file));
  if (check) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}

export function textsModule(): string {
  const entries: [string, string][] = [];
  for (const dir of readdirSync(SAMPLES_DIR, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
    for (const name of readdirSync(path.join(SAMPLES_DIR, dir)).filter((n) => n.endsWith('.md')).sort()) {
      entries.push([`${dir}/${name}`, readFileSync(path.join(SAMPLES_DIR, dir, name), 'utf8').replace(/\r\n/g, '\n')]);
    }
  }
  return (
    '// GENERATED by scripts/build-fixtures.ts from content/samples/*/*.md. Do not edit.\n' +
    'export const SAMPLE_TEXTS: Record<string, string> = {\n' +
    entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') +
    '\n};\n'
  );
}

/** The files a sample's deliverable puts under public/samples/<id>/. */
export function publicFiles(result: TaskResult): { path: string; text: string }[] {
  const d = result.deliverable;
  if (d?.kind === 'site') return d.files.map((f) => ({ path: f.path, text: f.text }));
  if (d?.kind === 'plan') {
    return [
      { path: 'index.html', text: toPlanPage(result, { csv: 'plan.csv', ics: 'plan.ics' }) },
      { path: 'plan.csv', text: toCsv(d) },
      { path: 'plan.ics', text: toIcs(d) },
    ];
  }
  return [];
}

async function main(): Promise<void> {
  put(path.join(SAMPLES_DIR, 'texts.generated.ts'), textsModule());
  if (process.argv.includes('--texts')) return report();
  // Imported after the texts are written: the samples module reads them.
  const { SAMPLE_IDS } = await import('../content/samples');
  const { runSample } = await import('../content/answers/run');
  for (const id of SAMPLE_IDS as SampleId[]) {
    const file = path.join(ANSWERS_DIR, `${id}.live.json`);
    if (!existsSync(file)) {
      console.log(`${id}: no recording yet (npm run record -- ${id})`);
      continue;
    }
    const set = JSON.parse(readFileSync(file, 'utf8')) as AnswerSet;
    const record = await runSample(id, set, { pace: 1, virtual: true });
    const result = record.result as TaskResult | null;
    if (record.status !== 'ready' || !result) throw new Error(`${id}: the replay ended ${record.status}`);
    put(path.join(ANSWERS_DIR, `${id}.events.json`), JSON.stringify(record.events.map((e) => ({ ...e, runId: `saved-${id}` }))) + '\n');
    const files = publicFiles(result);
    const dir = path.join(PUBLIC_DIR, id);
    const keep = new Set(files.map((f) => path.normalize(f.path)));
    if (existsSync(dir)) {
      for (const name of readdirSync(dir, { recursive: true }) as string[]) {
        const full = path.join(dir, name);
        if (!keep.has(path.normalize(name)) && statSync(full).isFile()) {
          stale.push(path.relative(ROOT, full));
          if (!check) rmSync(full);
        }
      }
    }
    for (const f of files) put(path.join(dir, f.path), f.text);
    const s = result.stats;
    console.log(`${id}: ${files.length} files, planted ${s.planted}, caught ${s.caught}`);
  }
  report();
}

function report(): void {
  if (!stale.length) console.log('Everything is up to date.');
  else if (check) {
    console.error(`Out of date (run npm run fixtures):\n${stale.map((s) => '  ' + s).join('\n')}`);
    process.exit(1);
  } else console.log(`Wrote:\n${stale.map((s) => '  ' + s).join('\n')}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.stack : e);
    process.exit(1);
  });
}
