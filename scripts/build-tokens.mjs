#!/usr/bin/env node
/**
 * Generates src/tokens/tokens.css from src/tokens/tokens.ts.
 *
 *   node scripts/build-tokens.mjs           write the file
 *   node scripts/build-tokens.mjs --check   exit 1 if the file on disk is out of date
 *
 * tokens.ts is the only source of values. The CSS file is committed so that the page
 * shell needs no build step, and tests/tokens.test.ts fails when the two drift apart.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const TOKENS_TS = resolve(root, 'src/tokens/tokens.ts');
export const TOKENS_CSS = resolve(root, 'src/tokens/tokens.css');

/** Loads tokens.ts as a module. The file imports nothing, so one transform is enough. */
export async function loadTokens() {
  const { transformWithEsbuild } = await import('vite');
  const source = await readFile(TOKENS_TS, 'utf8');
  const { code } = await transformWithEsbuild(source, TOKENS_TS, {
    loader: 'ts',
    format: 'esm',
    target: 'es2022',
    sourcemap: false,
  });
  const url = `data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
  return import(url);
}

const kebab = (name) => name.replace(/[A-Z]+/g, (m) => `-${m.toLowerCase()}`);

/** Flattens nested colour groups: void.zenith -> color-void-zenith, ground.tile[1] -> color-ground-tile-2. */
function flatColors(prefix, value, out) {
  if (typeof value === 'string') {
    out.push([prefix, value]);
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => flatColors(`${prefix}-${i + 1}`, v, out));
  } else {
    for (const [k, v] of Object.entries(value)) flatColors(`${prefix}-${kebab(k)}`, v, out);
  }
  return out;
}

/** Returns the full text of tokens.css for the given token module. */
export function renderTokensCss(tokens) {
  const { COLOR, ROLE, WEB_TYPE, RADIUS, SHADOW, TARGET, MOTION, SKY } = tokens;
  const lines = [];
  const group = (title, entries) => {
    lines.push(`  /* ${title} */`);
    for (const [name, value] of entries) lines.push(`  --${name}: ${value};`);
    lines.push('');
  };
  const rawByValue = new Map();
  const raw = flatColors('color', COLOR, []);
  for (const [name, value] of raw) if (!rawByValue.has(value)) rawByValue.set(value, name);

  group('Colour, named as in DESIGN', raw);
  group(
    'What each colour is for',
    Object.entries(ROLE).map(([k, v]) => [`role-${kebab(k)}`, rawByValue.has(v) ? `var(--${rawByValue.get(v)})` : v]),
  );
  // The sky as the first paint of /app: the five stops of the dome, horizon on the top third.
  const stops = SKY.stops.map((s) => [s.el, s.color]);
  group('Sky of the first frame', [
    [
      'sky-gradient',
      `linear-gradient(180deg, ${stops[0][1]} 0%, ${stops[1][1]} 22%, ${stops[2][1]} 33%, ${stops[3][1]} 46%, ${stops[4][1]} 100%)`,
    ],
  ]);
  group('Type', [
    ['font-family', WEB_TYPE.family],
    ...Object.entries(WEB_TYPE.scale).map(([k, v]) => [`text-${kebab(k)}`, `${v}px`]),
    ['body-leading', WEB_TYPE.body.leading],
    ['body-weight', WEB_TYPE.body.weight],
    ['display-size', `${WEB_TYPE.display.size}px`],
    ['display-size-phone', `${WEB_TYPE.display.sizePhone}px`],
    ['display-weight', WEB_TYPE.display.weight],
    ['display-tracking', `${WEB_TYPE.display.trackingEm}em`],
    ['display-leading', WEB_TYPE.display.leading],
    ['heading-weight', WEB_TYPE.heading.weight],
    ['heading-tracking', `${WEB_TYPE.heading.trackingEm}em`],
    ['heading-leading', WEB_TYPE.heading.leading],
    ['label-weight', WEB_TYPE.label.weight],
  ]);
  group('Geometry', [
    ...Object.entries(RADIUS.web).map(([k, v]) => [`radius-${kebab(k)}`, `${v}px`]),
    ['button-height', `${TARGET.web.button}px`],
    ['control-height', `${TARGET.web.control}px`],
    ['focus-ring', `${TARGET.web.focusRing}px`],
    ['focus-offset', `${TARGET.web.focusOffset}px`],
  ]);
  group('Elevation', Object.entries(SHADOW).map(([k, v]) => [`shadow-${kebab(k)}`, v]));
  group('Motion', [
    ['dur-hover', `${MOTION.web.hoverMs}ms`],
    ['dur-press', `${MOTION.web.pressMs}ms`],
    ['dur-release', `${MOTION.web.releaseMs}ms`],
    ['dur-reveal', `${MOTION.firstFrame.fadeMs}ms`],
    ['hover-lift', `${MOTION.web.lift}px`],
    ['press-scale', MOTION.web.pressScale],
    ['ease', MOTION.web.ease],
    ['ease-release', MOTION.web.easeRelease],
  ]);
  lines.pop();

  const out = [
    '/* Generated by scripts/build-tokens.mjs from src/tokens/tokens.ts. Do not edit:',
    '   change tokens.ts and run "npm run tokens". */',
    ':root {',
    ...lines,
    '}',
  ];
  return `${out.join('\n')}\n`;
}

async function main() {
  const css = renderTokensCss(await loadTokens());
  if (process.argv.includes('--check')) {
    const onDisk = await readFile(TOKENS_CSS, 'utf8').catch(() => '');
    if (onDisk.replace(/\r\n/g, '\n') !== css) {
      console.error('src/tokens/tokens.css is out of date. Run "npm run tokens".');
      process.exit(1);
    }
    console.log('src/tokens/tokens.css is up to date.');
    return;
  }
  await writeFile(TOKENS_CSS, css);
  console.log(`Wrote ${TOKENS_CSS}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
